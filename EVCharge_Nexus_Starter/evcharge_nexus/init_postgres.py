from database import get_connection

STATEMENTS = [
    """
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS vehicles (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id),
        manufacturer TEXT NOT NULL,
        model TEXT NOT NULL,
        battery_kwh REAL NOT NULL CHECK(battery_kwh > 0),
        connector TEXT NOT NULL,
        current_soc INTEGER NOT NULL CHECK(current_soc BETWEEN 0 AND 100),
        target_soc INTEGER NOT NULL CHECK(target_soc BETWEEN 0 AND 100),
        created_at TEXT NOT NULL
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS reservations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        reference TEXT NOT NULL UNIQUE,
        user_id INTEGER NOT NULL,
        vehicle_id INTEGER NOT NULL,
        station_key TEXT NOT NULL,
        station_name TEXT NOT NULL,
        station_city TEXT NOT NULL,
        station_address TEXT NOT NULL,
        station_lat REAL,
        station_lng REAL,
        connector TEXT NOT NULL,
        start_at TEXT NOT NULL,
        end_at TEXT NOT NULL,
        current_soc INTEGER NOT NULL,
        target_soc INTEGER NOT NULL,
        energy_kwh REAL NOT NULL,
        estimated_cost REAL,
        status TEXT NOT NULL DEFAULT 'confirmed',
        created_at TEXT NOT NULL
    )
    """,

    """
    CREATE INDEX IF NOT EXISTS idx_reservation_slots
    ON reservations (station_key, status, start_at, end_at)
    """,

    """
    CREATE INDEX IF NOT EXISTS idx_reservation_user
    ON reservations (user_id, start_at)
    """,

    """
    CREATE TABLE IF NOT EXISTS notifications (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        reservation_reference TEXT,
        kind TEXT NOT NULL,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        is_read INTEGER NOT NULL DEFAULT 0 CHECK(is_read IN (0, 1)),
        created_at TEXT NOT NULL,
        UNIQUE(user_id, reservation_reference, kind)
    )
    """,

    """
    CREATE INDEX IF NOT EXISTS idx_notifications_user
    ON notifications (user_id, is_read, created_at DESC)
    """,

    """
    CREATE TABLE IF NOT EXISTS push_subscriptions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        endpoint TEXT NOT NULL UNIQUE,
        subscription_json TEXT NOT NULL,
        created_at TEXT NOT NULL
    )
    """,

    """
    CREATE INDEX IF NOT EXISTS idx_push_user
    ON push_subscriptions (user_id)
    """
]


def main():
    conn = get_connection()

    try:
        with conn:
            with conn.cursor() as cursor:
                for sql in STATEMENTS:
                    cursor.execute(sql)

                cursor.execute("""
                    SELECT table_name
                    FROM information_schema.tables
                    WHERE table_schema = 'public'
                    ORDER BY table_name
                """)

                tables = [
                    row["table_name"]
                    for row in cursor.fetchall()
                ]

        print("PostgreSQL schema initialized successfully!")

        for table in tables:
            print(table)

    finally:
        conn.close()


if __name__ == "__main__":
    main()
