@notifications_bp.get("/api/notifications")
def list_notifications():

    user_id = current_user()

    if not user_id:

        return error("Please sign in.", 401)

    db = db_connection()

    new_reminders = []

    try:

        new_reminders = generate_reminders(
            db,
            user_id
        )

        rows = db.execute("""
            SELECT
                id,
                reservation_reference,
                kind,
                title,
                message,
                is_read,
                created_at
            FROM notifications
            WHERE user_id = ?
            ORDER BY created_at DESC, id DESC
            LIMIT 100
        """, (
            user_id,
        )).fetchall()

        unread = db.execute("""
            SELECT COUNT(*) AS total
            FROM notifications
            WHERE user_id = ?
              AND is_read = 0
        """, (
            user_id,
        )).fetchone()["total"]

        result = {
            "notifications": [
                dict(row)
                for row in rows
            ],
            "unread_count": unread
        }

        db.commit()

    except psycopg2.Error:

        db.rollback()

        current_app.logger.exception(
            "Notification retrieval failed"
        )

        return error(
            "Unable to load notifications.",
            500
        )

    finally:

        db.close()

    # Send newly created reminders after commit

    deliver_reminders(new_reminders)

    return jsonify(result)


